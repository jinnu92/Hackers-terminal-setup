#!/usr/bin/env bash
# =============================================================================
#  bundle.sh — Hackers Terminal Setup Distribution Compiler
#  Compiles modular lib/*.sh into a standalone, single-file curl-pipeable script
# =============================================================================

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUTPUT_FILE="$SCRIPT_DIR/ter.sh"
TEMP_FILE="$(mktemp)"

echo -e "\033[0;36m[*] Bundling modular Hackers Terminal Setup into standalone ter.sh...\033[0m"

# Header
cat > "$TEMP_FILE" << 'EOF'
#!/usr/bin/env bash
# =============================================================================
#  SECURITY TERMINAL SETUP — BEST-IN-CLASS 2.0 (STANDALONE DISTRIBUTION)
#  Single unified script — macOS & Linux
#  Auto-generated by bundle.sh. To modify, edit lib/*.sh and re-run ./bundle.sh.
# =============================================================================

set -e

# If running directly from cloned repo with lib/ present, source modules dynamically for live development
# Piped mode (curl | bash): BASH_SOURCE[0] is empty at top level, so the script text
# itself is arriving on stdin. Record that here (top level is the only reliable place;
# inside functions BASH_SOURCE[0] is not empty) and never source lib/ from the cwd.
if [[ -n "${BASH_SOURCE[0]:-}" && -f "${BASH_SOURCE[0]}" ]]; then
  _HTS_PIPED=0
  _HTS_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
  if [[ -d "$_HTS_ROOT/lib" ]]; then
    for _mod in common versions pkg_mgr helpers preflight fonts dev terminals shell_tools ad_pivoting web_api cloud_devsec mobile_re pentest bugbounty cloud ai_mcp workflow dashboard doctor configs lifecycle menu; do
      [[ -f "$_HTS_ROOT/lib/${_mod}.sh" ]] && source "$_HTS_ROOT/lib/${_mod}.sh"
    done
  fi
else
  _HTS_PIPED=1
fi

EOF


# Modules in strict dependency order
MODULES=(
  "lib/common.sh"
  "lib/versions.sh"
  "lib/pkg_mgr.sh"
  "lib/helpers.sh"
  "lib/preflight.sh"
  "lib/fonts.sh"
  "lib/dev.sh"
  "lib/terminals.sh"
  "lib/shell_tools.sh"
  "lib/ad_pivoting.sh"
  "lib/web_api.sh"
  "lib/cloud_devsec.sh"
  "lib/mobile_re.sh"
  "lib/pentest.sh"
  "lib/bugbounty.sh"
  "lib/cloud.sh"
  "lib/ai_mcp.sh"
  "lib/workflow.sh"
  "lib/dashboard.sh"
  "lib/doctor.sh"
  "lib/configs.sh"
  "lib/lifecycle.sh"
  "lib/menu.sh"
)

for mod in "${MODULES[@]}"; do
  mod_path="$SCRIPT_DIR/$mod"
  if [[ -f "$mod_path" ]]; then
    echo "  -> Adding $mod"
    echo -e "\n# ─── Begin: $mod ──────────────────────────────────────────" >> "$TEMP_FILE"
    # Filter out initial shebangs from individual modules
    grep -v '^#!/usr/bin/env bash' "$mod_path" >> "$TEMP_FILE"
    echo -e "\n# ─── End: $mod ────────────────────────────────────────────" >> "$TEMP_FILE"
  else
    echo -e "\033[0;31m[-] Error: Missing module $mod\033[0m" >&2
    exit 1
  fi
done

# Append Entry Point
cat >> "$TEMP_FILE" << 'EOF'

# =============================================================================
# ENTRY POINT
# =============================================================================
# Everything runs inside one function that is called on the very last line, so
# bash has parsed the whole script before any installer starts. This matters for
# `curl ... | bash`: a child process that reads stdin can no longer swallow the
# rest of the script.
hts_help() {
      echo ""
      echo -e "${BOLD}${CYAN}Hackers Terminal Setup ${HTS_VERSION} — CLI Options${RESET}"
      echo ""
      echo "Usage: ./ter.sh [OPTIONS] [NUMBERS...]"
      echo "   or: curl -fsSL https://raw.githubusercontent.com/jinnu92/Hackers-terminal-setup/main/ter.sh | bash -s -- [OPTIONS]"
      echo ""
      echo "Options:"
      echo "  -y, --yes        Unattended mode (install all with zero [y/n] prompts)"
      echo "  -a, --all        Install all components"
      echo "  --core           Install core terminal tools (OMZ, p10k, fzf, bat, etc.)"
      echo "  --fonts          Install Hacker & Developer Nerd Fonts"
      echo "  --node           Install Node.js LTS and configure safe npm prefix"
      echo "  --claude         Install Claude Code CLI (@anthropic-ai/claude-code)"
      echo "  --code           Install Visual Studio Code & 'code' CLI"
      echo "  --dev            Install complete dev stack (Node + Claude Code + VS Code)"
      echo "  --terminals      Install modern GPU terminal emulators (Ghostty/WezTerm/Kitty)"
      echo "  --shell-tools    Install Atuin (SQLite history), direnv, uv, btop, yazi, Starship"
      echo "  --mcp            Install preconfigured safe MCP Server Suite & sec-mcp CLI"
      echo "  --pentest        Install pentest tools (nmap, sqlmap, hydra, john, SecLists)"
      echo "  --seclists       Download SecLists directly from GitHub to ~/pentest/wordlists"
      echo "  --bugbounty      Install bug bounty tools (subfinder, httpx, nuclei, ffuf, katana)"
      echo "  --ad-pivot       Install Active Directory & Pivoting tools (Ligolo-ng, Chisel, NetExec)"
      echo "  --web-api        Install Web & API security tools (Schemathesis, Kiterunner, Caido, Arjun)"
      echo "  --devsecops      Install Container & DevSecOps tools (Trivy, Syft, Grype, Checkov)"
      echo "  --mobile         Install Mobile & Reverse Engineering tools (Jadx, Apktool)"
      echo "  --cloud          Install cloud security tools (AWS CLI, Azure, gcloud, prowler)"
      echo "  --ai             Install AI / LLM security tools"
      echo "  --workflow       Install workflow tools"
      echo "  --dashboard      Install Fastfetch & Tactical Security Welcome Cockpit"
      echo "  --config         Write configuration files (.zshrc, pentest.zsh, etc.)"
      echo "  -d, --doctor     Run system diagnostic audit (works in any position)"
      echo "  -n, --dry-run    Show what would be installed or written, change nothing"
      echo "      --list       List all components (number, flag, name, contents) and exit"
      echo "      --json       With --doctor: machine-readable JSON output (no banner/summary)"
      echo "  -V, --version    Print the version and exit"
      echo "  -h, --help       Show this help message"
      echo ""
      echo "Lifecycle (run alone; no preflight, cannot be combined with components):"
      echo "  --status             Show installed components, tracked tools/files, backup runs, log/manifest paths"
      echo "  --restore [TS]       Restore backed-up files (default: earliest backup of each file); -y, --dry-run"
      echo "  --uninstall          Restore backups / remove files this tool created (tools are only listed)"
      echo "  --purge-tools        With --uninstall: also remove manifest-recorded tools via their package manager"
      echo "  --update             Check for a newer release; upgrade manifest-recorded tools"
      echo "  Works piped too:     curl -fsSL <url>/ter.sh | bash -s -- --status"
      echo ""
      echo "Unknown options are an error: nothing runs until the whole selection is valid."
      echo "Each component runs independently; a results summary and log"
      echo "(~/.local/state/hts/install.log) are produced, and the exit code is non-zero"
      echo "if any step failed. Replaced dotfiles are backed up under ~/.local/state/hts/backups."
      echo ""
      echo "Examples:"
      echo "  ./ter.sh -y                               # Completely unattended zero-prompt install"
      echo "  ./ter.sh                                  # Launch interactive menu (press Enter or 'y' for all)"
      echo "  ./ter.sh --all                            # Install complete hacker terminal"
      echo "  ./ter.sh -y --fonts --dev --mcp           # Install selected tools unattended"
      echo "  ./ter.sh --ad-pivot --web-api --devsecops # Install comprehensive assessment suite"
      echo "  ./ter.sh --doctor                         # Audit current environment & tools"
      echo "  ./ter.sh --dry-run --all                  # Preview everything, change nothing"
      echo "  ./ter.sh --list                           # Show the component table"
      echo ""
}

_hts_main() {
  # Informational flags win over everything else and touch nothing.
  local _a
  for _a in "$@"; do
    case "$_a" in
      -h|--help|help)  hts_help; exit 0 ;;
      -V|--version)    echo "Hackers Terminal Setup $HTS_VERSION"; exit 0 ;;
      --list)          hts_list_components; exit 0 ;;
    esac
  done

  # Lifecycle commands (--status/--restore/--uninstall/--update) are validated first and
  # never reach preflight or any install function. --json is consumed here.
  hts_lifecycle_parse "$@" || exit 2
  if [[ -n "$HTS_LC_CMD" ]]; then
    hts_lifecycle_run
    exit $?
  fi
  set -- "${HTS_PASSTHRU[@]}"
  if [[ "${HTS_DOCTOR_FORMAT:-}" == "json" ]] && hts_doctor_only_args "$@"; then
    detect_os >/dev/null    # JSON on stdout only: no OS lines, banner or summary
    sec_doctor
    exit $?
  fi

  HTS_RUN_RC=0
  HTS_SHOW_BANNER=0
  if [[ $# -gt 0 ]]; then
    # Validates the whole selection, then (for a real run) detects the OS and acts.
    run_selections "$@"
  else
    detect_os
    show_menu
    run_selections "$choices"
  fi

  # ─── Post-install summary ───────────────────────────────────────────────────
  if [[ "$HTS_SHOW_BANNER" -eq 1 ]]; then
    hts_print_banner "$HTS_RUN_RC"
  fi
  exit "$HTS_RUN_RC"
}

_hts_main "$@"
EOF

mv "$TEMP_FILE" "$OUTPUT_FILE"
chmod +x "$OUTPUT_FILE"

echo -e "\033[0;32m[✓] Successfully compiled standalone $OUTPUT_FILE ($(wc -l < "$OUTPUT_FILE") lines)!\033[0m"
