#!/usr/bin/env bash
# =============================================================================
#  bundle.sh — Hackers Terminal Setup Distribution Compiler
#  Compiles modular lib/*.sh into a standalone, single-file curl-pipeable script
# =============================================================================

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUTPUT_FILE="$SCRIPT_DIR/ter.sh"
TEMP_FILE="$(mktemp)"

echo -e "\033[0;36m[*] Bundling modular Hackers Terminal Setup into standalone ter.sh...\033[0m"

# Header
cat > "$TEMP_FILE" << 'EOF'
#!/usr/bin/env bash
# =============================================================================
#  SECURITY TERMINAL SETUP — BEST-IN-CLASS 2.0 (STANDALONE DISTRIBUTION)
#  Single unified script — macOS & Linux
#  Auto-generated by bundle.sh. To modify, edit lib/*.sh and re-run ./bundle.sh.
# =============================================================================

set -e

# If running directly from cloned repo with lib/ present, source modules dynamically for live development
_HTS_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
if [[ -d "$_HTS_ROOT/lib" ]]; then
  for _mod in common pkg_mgr helpers preflight fonts dev terminals shell_tools ad_pivoting web_api cloud_devsec mobile_re pentest bugbounty cloud ai_mcp workflow dashboard doctor configs menu; do
    [[ -f "$_HTS_ROOT/lib/${_mod}.sh" ]] && source "$_HTS_ROOT/lib/${_mod}.sh"
  done
fi

EOF


# Modules in strict dependency order
MODULES=(
  "lib/common.sh"
  "lib/pkg_mgr.sh"
  "lib/helpers.sh"
  "lib/preflight.sh"
  "lib/fonts.sh"
  "lib/dev.sh"
  "lib/terminals.sh"
  "lib/shell_tools.sh"
  "lib/ad_pivoting.sh"
  "lib/web_api.sh"
  "lib/cloud_devsec.sh"
  "lib/mobile_re.sh"
  "lib/pentest.sh"
  "lib/bugbounty.sh"
  "lib/cloud.sh"
  "lib/ai_mcp.sh"
  "lib/workflow.sh"
  "lib/dashboard.sh"
  "lib/doctor.sh"
  "lib/configs.sh"
  "lib/menu.sh"
)

for mod in "${MODULES[@]}"; do
  mod_path="$SCRIPT_DIR/$mod"
  if [[ -f "$mod_path" ]]; then
    echo "  -> Adding $mod"
    echo -e "\n# ─── Begin: $mod ──────────────────────────────────────────" >> "$TEMP_FILE"
    # Filter out initial shebangs from individual modules
    grep -v '^#!/usr/bin/env bash' "$mod_path" >> "$TEMP_FILE"
    echo -e "\n# ─── End: $mod ────────────────────────────────────────────" >> "$TEMP_FILE"
  else
    echo -e "\033[0;31m[-] Error: Missing module $mod\033[0m" >&2
    exit 1
  fi
done

# Append Entry Point
cat >> "$TEMP_FILE" << 'EOF'

# =============================================================================
# ENTRY POINT
# =============================================================================
detect_os

if [[ $# -gt 0 ]]; then
  case "$1" in
    -h|--help|help)
      echo ""
      echo -e "${BOLD}${CYAN}Hackers Terminal Setup 2.0 — CLI Options${RESET}"
      echo ""
      echo "Usage: ./ter.sh [OPTIONS] [NUMBERS...]"
      echo ""
      echo "Options:"
      echo "  -y, --yes        Unattended mode (install all with zero [y/n] prompts)"
      echo "  -a, --all        Install all components"
      echo "  --core           Install core terminal tools (OMZ, p10k, fzf, bat, etc.)"
      echo "  --fonts          Install Hacker & Developer Nerd Fonts"
      echo "  --node           Install Node.js LTS and configure safe npm prefix"
      echo "  --claude         Install Claude Code CLI (@anthropic-ai/claude-code)"
      echo "  --code           Install Visual Studio Code & 'code' CLI"
      echo "  --dev            Install complete dev stack (Node + Claude Code + VS Code)"
      echo "  --terminals      Install modern GPU terminal emulators (Ghostty/WezTerm/Kitty)"
      echo "  --shell-tools    Install Atuin (SQLite history), direnv, uv, btop, yazi, Starship"
      echo "  --mcp            Install preconfigured safe MCP Server Suite & sec-mcp CLI"
      echo "  --pentest        Install pentest tools (nmap, sqlmap, hydra, john, SecLists)"
      echo "  --seclists       Download SecLists directly from GitHub to ~/pentest/wordlists"
      echo "  --bugbounty      Install bug bounty tools (subfinder, httpx, nuclei, ffuf, katana)"
      echo "  --ad-pivot       Install Active Directory & Pivoting tools (Ligolo-ng, Chisel, NetExec)"
      echo "  --web-api        Install Web & API security tools (Schemathesis, Kiterunner, Caido, Arjun)"
      echo "  --devsecops      Install Container & DevSecOps tools (Trivy, Syft, Grype, Checkov)"
      echo "  --mobile         Install Mobile & Reverse Engineering tools (Jadx, Apktool)"
      echo "  --cloud          Install cloud security tools (AWS CLI, Azure, gcloud, prowler)"
      echo "  --ai             Install AI / LLM security tools"
      echo "  --workflow       Install workflow tools"
      echo "  --dashboard      Install Fastfetch & Tactical Security Welcome Cockpit"
      echo "  --config         Write configuration files (.zshrc, pentest.zsh, etc.)"
      echo "  -d, --doctor     Run system diagnostic audit"
      echo "  -h, --help       Show this help message"
      echo ""
      echo "Examples:"
      echo "  ./ter.sh -y                               # Completely unattended zero-prompt install"
      echo "  ./ter.sh                                  # Launch interactive menu (press Enter or 'y' for all)"
      echo "  ./ter.sh --all                            # Install complete hacker terminal"
      echo "  ./ter.sh -y --fonts --dev --mcp           # Install selected tools unattended"
      echo "  ./ter.sh --ad-pivot --web-api --devsecops # Install comprehensive assessment suite"
      echo "  ./ter.sh --doctor                         # Audit current environment & tools"
      echo ""
      exit 0
      ;;
    *)
      run_selections "$@"
      ;;
  esac
else
  show_menu
  run_selections "$choices"
fi

# ─── Post-install summary ─────────────────────────────────────────────────────
echo ""
echo -e "${BOLD}${GREEN}════════════════════════════════════════════════════════════════════${RESET}"
echo -e "${BOLD}${GREEN}  Setup Complete!${RESET}"
echo -e "${BOLD}${GREEN}════════════════════════════════════════════════════════════════════${RESET}"
echo ""
echo -e "  ${CYAN}Next steps:${RESET}"
echo -e "  1. ${YELLOW}Set terminal font:${RESET}  'MesloLGS NF' (p10k) or 'JetBrainsMono Nerd Font'"
echo -e "  2. ${YELLOW}Reload shell:${RESET}       ${BOLD}exec zsh${RESET}"
echo -e "  3. ${YELLOW}Configure prompt:${RESET}   ${BOLD}p10k configure${RESET} (or Starship: ${BOLD}starship.toml${RESET})"
echo -e "  4. ${YELLOW}Start Claude Code:${RESET}  ${BOLD}claude${RESET} (or ${BOLD}cc${RESET})"
echo -e "  5. ${YELLOW}Manage MCP suite:${RESET}   ${BOLD}sec-mcp list${RESET} or ${BOLD}sec-mcp inspect${RESET}"
echo -e "  6. ${YELLOW}Run Atuin history:${RESET}  ${BOLD}Ctrl+R${RESET} (scrubs tokens automatically)"
echo -e "  7. ${YELLOW}Run System Doctor:${RESET}  ${BOLD}doctor${RESET} (or ${BOLD}sec-doctor${RESET})"
echo -e "  8. ${YELLOW}Open cheat sheet:${RESET}   ${BOLD}cheat${RESET} or ${BOLD}?${RESET}"
echo ""
EOF

mv "$TEMP_FILE" "$OUTPUT_FILE"
chmod +x "$OUTPUT_FILE"

echo -e "\033[0;32m[✓] Successfully compiled standalone $OUTPUT_FILE ($(wc -l < "$OUTPUT_FILE") lines)!\033[0m"
